/**
 * Generates styles/scopes.css: a `.light` class carrying the light-mode semantic colours of
 * styles/tokens.css, so a light panel can sit inside a dark page (docs previews, tokens page).
 * Values are copied from tokens.css, never typed by hand. Run: pnpm styles:build
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const tokens = readFileSync(root("styles/tokens.css"), "utf8");

// Names overridden by `.dark` = the mode-dependent ones.
const darkBlock = tokens.match(/\.dark\s*\{([^}]*)\}/)?.[1] ?? "";
const modeVars = new Set([...darkBlock.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]));

const rootBlock = tokens.match(/:root\s*\{([^}]*)\}/)?.[1] ?? "";
const lines = [...rootBlock.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)]
  .filter((m) => modeVars.has(m[1]))
  .map((m) => `  ${m[1]}: ${m[2].trim()};`);

// Aliases (`--card: var(--surface)`) resolve where they are declared, so a nested scope must
// redeclare them or they would keep the page's mode.
const aliases = [...rootBlock.matchAll(/(--[\w-]+)\s*:\s*(var\(--[^;]+\));/g)]
  .filter((m) => !m[1].startsWith("--dither-") && !modeVars.has(m[1]))
  .map((m) => `  ${m[1]}: ${m[2].trim()};`);

if (lines.length !== modeVars.size) {
  throw new Error(`light scope: expected ${modeVars.size} vars, found ${lines.length}`);
}

writeFileSync(
  root("styles/scopes.css"),
  `/* GENERATED by scripts/build-light-scope.ts from tokens.css — do not edit by hand. */

.light {
${lines.join("\n")}
${aliases.join("\n")}
  color-scheme: light;
}

.dark {
${aliases.join("\n")}
  color-scheme: dark;
}
`,
);
console.log(`light scope: ${lines.length} vars, ${aliases.length} aliases`);
