/**
 * Generates styles/dither.css (Tailwind v4 utilities) from registry/dither/lib/dither-tile.ts.
 * Run: pnpm dither:css
 *
 * The texture is applied as a CSS mask over `background-color: var(--dither-color)`,
 * so it follows the tokens (light / dark) — a data-URI background could not read currentColor.
 * Because a mask also clips children, put the utility on a dedicated layer
 * (e.g. <span class="bg-dither absolute inset-0" />), not on an element with content.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { DITHER_VARIANTS, ditherTile, ditherTileSvg, organicTile } from "../registry/dither/lib/dither-tile.ts";

const uri = (svg: string) => `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, "%27")}")`;

let css = `/* GENERATED by scripts/build-dither-css.ts — do not edit by hand.
   Override the dot colour per element with --dither-color (defaults to --border-strong). */
`;

for (const variant of DITHER_VARIANTS) {
  const tile = ditherTile(variant);
  const name = variant === "regular" ? "bg-dither" : `bg-dither-${variant}`;
  const repeat = variant === "gradient" ? "repeat-x" : "repeat";
  css += `
@utility ${name} {
  background-color: var(--dither-color, var(--border-strong));
  -webkit-mask-image: ${uri(ditherTileSvg(variant))};
  mask-image: ${uri(ditherTileSvg(variant))};
  -webkit-mask-size: ${tile.width}px ${tile.height}px;
  mask-size: ${tile.width}px ${tile.height}px;
  -webkit-mask-repeat: ${repeat};
  mask-repeat: ${repeat};
}
`;
}

// Cursor glow: a small organic dither (clumps, 1 → 2px dots), visible only inside a soft radial
// spot at (--x, --y) that fades out from the centre (no hard core, no visible grid).
// Set --x / --y (px or %) from a pointer handler; --glow-r sets the radius.
{
  const tile = organicTile({ size: 72, cell: 3, dot: [1, 2], period: 3, seed: 3 });
  const rects = tile.dots.map((d) => `<rect x='${d.x}' y='${d.y}' width='${d.size}' height='${d.size}'/>`).join("");
  const dots = uri(`<svg xmlns='http://www.w3.org/2000/svg' width='${tile.size}' height='${tile.size}' fill='#000'>${rects}</svg>`);
  const spot = "radial-gradient(circle var(--glow-r, 64px) at var(--x, 50%) var(--y, 50%), #000 0%, rgb(0 0 0 / 0.35) 45%, transparent 85%)";
  css += `
@utility bg-dither-glow {
  background-color: var(--dither-color, var(--border-strong));
  -webkit-mask-image: ${spot}, ${dots};
  mask-image: ${spot}, ${dots};
  -webkit-mask-size: 100% 100%, ${tile.size}px ${tile.size}px;
  mask-size: 100% 100%, ${tile.size}px ${tile.size}px;
  -webkit-mask-repeat: no-repeat, repeat;
  mask-repeat: no-repeat, repeat;
  -webkit-mask-composite: source-in;
  mask-composite: intersect;
}
`;
}

// Skeleton sweep: the organic tile, seen through a soft band that travels left → right.
// Animate with `animate-dither-sweep` (styles/motion.css); off under reduced motion.
{
  const tile = ditherTile("organic");
  const dots = uri(ditherTileSvg("organic"));
  const band = "linear-gradient(90deg, transparent 0%, #000 40%, #000 60%, transparent 100%)";
  css += `
@utility bg-dither-sweep {
  background-color: var(--dither-color, var(--border-strong));
  -webkit-mask-image: ${band}, ${dots};
  mask-image: ${band}, ${dots};
  -webkit-mask-size: 50% 100%, ${tile.width}px ${tile.height}px;
  mask-size: 50% 100%, ${tile.width}px ${tile.height}px;
  -webkit-mask-repeat: no-repeat, repeat;
  mask-repeat: no-repeat, repeat;
  -webkit-mask-position: -100% 0, 0 0;
  mask-position: -100% 0, 0 0;
  -webkit-mask-composite: source-in;
  mask-composite: intersect;
}
`;
}

const out = fileURLToPath(new URL("../styles/dither.css", import.meta.url));
writeFileSync(out, css);
console.log(`wrote ${out}`);
